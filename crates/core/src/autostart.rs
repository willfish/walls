/// Whether tray autostart can be configured on this desktop.
pub fn tray_autostart_available(desktop: Desktop) -> bool {
    unsupported_tray_reason(desktop).is_none()
}

/// Read per-desktop autostart flag from config.
pub fn tray_autostart_enabled_for_desktop(config: &Config, desktop: Desktop) -> bool {
    config
        .tray
        .autostart
        .desktops
        .get(desktop_config_key(desktop))
        .copied()
        .unwrap_or(false)
}

/// Set per-desktop autostart flag in config.
pub fn set_tray_autostart_for_desktop(config: &mut Config, desktop: Desktop, enabled: bool) {
    config
        .tray
        .autostart
        .desktops
        .insert(desktop_config_key(desktop).into(), enabled);
}

/// Enabled `OnlyShowIn` entries from config, skipping unsupported desktops.
pub fn enabled_autostart_only_show_in(
    desktops: &impl std::borrow::Borrow<HashMap<String, bool>>,
) -> Vec<&'static str> {
    let desktops = desktops.borrow();
    let mut tokens = Vec::new();
    for (key, enabled) in desktops {
        if !enabled {
            continue;
        }
        if let Some(desktop) = desktop_from_config_key(key) {
            if tray_autostart_available(desktop) {
                tokens.push(desktop_only_show_in(desktop));
            }
        }
    }
    tokens.sort_unstable();
    tokens.dedup();
    tokens
}

