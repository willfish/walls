//! Sync tray login autostart via XDG `autostart/*.desktop`.

use std::collections::HashMap;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

use crate::apply::{detect_desktop, Desktop};
use crate::bin_resolve::{resolve_binary, BinResolveOpts};
use crate::config::Config;
use crate::tray::{session_type_from_env, unsupported_tray_reason};

const AUTOSTART_FILENAME: &str = "walls-tray.desktop";
const GENERATED_MARKER: &str = "Generated by walls";

/// Inputs for [`sync_tray_autostart_with`] (testable).
#[derive(Debug, Clone)]
pub struct AutostartSyncOpts<'a> {
    pub config_home: &'a Path,
    pub tray_bin: PathBuf,
    pub config: &'a Config,
    pub xdg_current_desktop: Option<&'a str>,
    pub xdg_session_desktop: Option<&'a str>,
    pub desktop_startup_id: Option<&'a str>,
    pub xdg_session_type: Option<&'a str>,
    pub wayland_display: Option<&'a str>,
    pub display: Option<&'a str>,
}

/// Outcome of syncing tray autostart.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum AutostartSyncOutcome {
    Written,
    Removed,
    WouldWrite { path: PathBuf },
    WouldRemove { path: PathBuf },
    Skipped { reason: String },
}

